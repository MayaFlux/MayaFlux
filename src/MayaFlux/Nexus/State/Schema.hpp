/**
 * @brief Current schema version written by StateEncoder and accepted by StateDecoder.
 *
 * History:
 *   1 - initial (positions only)
 *   2 - added color, size, wiring
 *   3 - added audio_sinks, render_sinks
 *   4 - added sink_type pixel row
 *   5 - added subkind, locus_nav fields, expanses array
 *   6 - entity position optional, entity orientation; locus_nav mouse_sensitivity,
 *       scroll_speed, aspect (up removed); wiring sources (key, mouse, network,
 *       window_event, factory, bind), scheduler tokens and callable names;
 *       render sink RenderConfig data; Expanse subkind (hull, mantle), collection
 *       and fit; Fabric cell_size
 *   7 - JSON keys are the member names, generated by MF_DESCRIBE. A key wiring
 *       also records key_modifiers when its key names modifiers. An entity's
 *       state is its controls: each slot of its store that holds a value is
 *       written by name as the text its TextCodec reads back, so nothing is
 *       listed by hand and a control added to an entity is saved without a
 *       change here. The EXR is a normalized picture of those same numbers and
 *       the decoder does not read it. Functions are written with their
 *       arguments, wirings with every trigger and ending, and buffers, windows
 *       and network sources by their bound names. Changed in place while
 *       unpublished.
 */
inline constexpr uint32_t k_schema_version = 7;

/**
 * @brief Oldest schema version StateDecoder reads. Version 7 changed its layout in
 *        place while unpublished, so no older file is read.
 */
inline constexpr uint32_t k_schema_min_version = 7;

/**
 * @brief RGBA32F EXR layout constant: the four values of a pixel are channels A, B, G, R in that order.
 *
 * One column per entity. Each numeric component of every control that any entity
 * holds is one value of a column, packed four to a pixel row in the order of
 * FabricSchema::components. A component an entity does not hold is 0.
 */
inline constexpr uint32_t k_channels = 4;

